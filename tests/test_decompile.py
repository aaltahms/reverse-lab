"""Import-boundary checks using the retained real provider output, not a mocked engine."""
import copy
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch
from lab.pipeline import ROOT,digest
from lab.webbuild import validate_assets
from lab.decompile import evidence_record,install_record,select_procedure

class ImportTests(unittest.TestCase):
    def setUp(self):
        self.temp=tempfile.TemporaryDirectory()
        self.root=Path(self.temp.name)
        self.record=json.loads((ROOT/'web/data/report.json').read_bytes())
        # This parser fixture replaces the full experiment with a provider-only
        # identity; its original evaluation receipt no longer applies.
        self.record.pop('evaluation', None)
        self.carrier=json.loads((ROOT/'web/data/providers/packet-O2-stripped.decompile.json').read_bytes())
        self.inventory=json.loads((ROOT/'web/data/providers/packet-O2-stripped.procedures.json').read_bytes())
        # The demo may be regenerated by CI without providers. Build a portable
        # recording identity from the real retained inventory for parser checks.
        address=self.carrier['data']['parameters']['procedure']
        self.variant={'id':'O2-stripped','artifact':'build/packet-O2-stripped',
                      'sha256':self.carrier['data']['subject']['digest']['sha256'],
                      'derivedFrom':{'procedureAddress':address,'selection':'Symbol-bearing twin; source known.'},'evidence':{}}
        self.record['fixtures']=[{'id':'packet','variants':[self.variant]}]
        self.report=self.root/'report.json'
        self.report.write_text(json.dumps(self.record))
        self.input=self.root/'decompile.json'
        self.procedures=self.root/'procedures.json'
        self.input.write_text(json.dumps(self.carrier))
        self.procedures.write_text(json.dumps(self.inventory))

    def tearDown(self):
        self.temp.cleanup()

    def import_record(self):
        with patch('lab.decompile.ROOT',self.root):
            return install_record(self.input,self.procedures,report_path=self.report,output_root=self.root/'web')

    def test_real_record_import_preserves_bytes_and_is_labeled_imported(self):
        evidence=self.import_record()
        self.assertEqual(evidence['output'],self.carrier['data']['normalized_result'])
        self.assertEqual(evidence['origin'],'imported-record')
        self.assertEqual(evidence['rawEvidenceSha256'],digest(self.input.read_bytes()))
        self.assertEqual((self.root/'web'/evidence['rawEvidencePath']).read_bytes(),self.input.read_bytes())
        self.assertEqual(json.loads(self.report.read_text())['providers'][0]['status'],'recorded')
        self.assertTrue(evidence['highlights'])

    def test_export_rejects_changed_raw_asset(self):
        evidence=self.import_record()
        recording=json.loads(self.report.read_text())
        validate_assets(recording,self.root/'web')
        path=self.root/'web'/evidence['rawEvidencePath']
        path.write_bytes(path.read_bytes()+b' ')
        with self.assertRaisesRegex(ValueError,'Provider asset hash mismatch'):
            validate_assets(recording,self.root/'web')

    def test_wrong_target_hash_is_rejected_without_changing_report(self):
        before=self.report.read_bytes()
        self.carrier['data']['subject']['digest']['sha256']='0'*64
        self.input.write_text(json.dumps(self.carrier))
        with self.assertRaisesRegex(ValueError,'target hash'):
            self.import_record()
        self.assertEqual(before,self.report.read_bytes())

    def test_cross_profile_record_is_rejected(self):
        self.carrier['data']['analysis_profile']['digest']='0'*64
        self.input.write_text(json.dumps(self.carrier))
        with self.assertRaisesRegex(ValueError,'different analysis profiles'):
            self.import_record()

    def test_null_pseudocode_stays_unknown(self):
        self.carrier['data']['normalized_result']=None
        self.input.write_text(json.dumps(self.carrier))
        with self.assertRaisesRegex(ValueError,'no pseudocode'):
            self.import_record()

    def test_error_data_inside_ok_envelope_is_not_success(self):
        with self.assertRaisesRegex(ValueError,'error record'):
            evidence_record({'ok':True,'data':{'error':'failed'}},'procedure_pseudo_code',self.variant['sha256'])

    def test_provider_or_operation_substitution_rejected(self):
        for key,value in [('operation','search_strings'),('provider',{'id':'other'})]:
            corrupt=copy.deepcopy(self.carrier)
            corrupt['data'][key]=value
            with self.assertRaisesRegex(ValueError,'operation/provider'):
                evidence_record(corrupt,'procedure_pseudo_code',self.variant['sha256'])

    def test_inventory_selection_requires_observed_unique_address(self):
        self.inventory['data']['normalized_result']=[]
        with self.assertRaisesRegex(ValueError,'unique Ghidra-observed'):
            select_procedure(self.inventory,self.variant)

    def test_stale_local_artifact_blocks_import(self):
        artifact=self.root/self.variant['artifact']
        artifact.parent.mkdir();artifact.write_bytes(b'wrong executable')
        with self.assertRaisesRegex(ValueError,'Local artifact changed'):
            self.import_record()

if __name__=='__main__':
    unittest.main()
