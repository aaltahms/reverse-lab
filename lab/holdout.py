"""Freeze known-source candidates, then evaluate previously unused inputs."""
import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import secrets

from lab.pipeline import ROOT, FIXTURES, cases_for, digest, oracle

REPORT = ROOT / 'web/data/report.json'
FREEZE = ROOT / 'web/data/evaluation-freeze.json'
LIMITATION = ('Reference source was known during candidate authorship. This is a '
              'local procedural freeze, not an authenticated history, independent '
              'analyst, source-blind challenge, or equivalence proof.')


def timestamp():
    return datetime.now(timezone.utc).isoformat()


def write_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix('.tmp')
    temporary.write_text(json.dumps(value, indent=2) + '\n')
    temporary.replace(path)


def case_stream(report):
    return [{k: case[k] for k in ('id', 'label', 'hex', 'group')}
            for case in report['cases']]


def stream_digest(cases):
    return digest(json.dumps(cases, sort_keys=True).encode())


def identity(record):
    """Bind every development corpus, candidate and artifact to the freeze."""
    result = []
    for fixture in record['fixtures']:
        name = fixture['id']
        if name not in FIXTURES:
            raise ValueError('Unknown fixture')
        variants = []
        for variant in fixture['variants']:
            if variant['id'] not in ('O0', 'O2', 'O2-stripped'):
                raise ValueError('Unknown variant')
            if variant['artifact'] != f"build/{name}-{variant['id']}":
                raise ValueError('Unexpected executable path')
            variants.append({k: variant[k] for k in ('id', 'artifact', 'sha256', 'harnessSha256')})
            for report in variant['reports']:
                if case_stream(report) != case_stream(fixture['variants'][0]['reports'][0]):
                    raise ValueError('Development corpora differ between candidates/builds')
                if stream_digest(case_stream(report)) != report['caseDigest']:
                    raise ValueError('Development corpus digest mismatch')
            if [r['id'] for r in variant['reports']] != FIXTURES[name]['candidates']:
                raise ValueError('Unexpected candidate list')
        for key, path in [('source', f'fixtures/{name}.c'),
                          ('reconstruction', f'reconstructions/{name}.py')]:
            if fixture[key]['path'] != path:
                raise ValueError('Unexpected source/candidate path')
        result.append({'id': name, 'candidateSha256': fixture['reconstruction']['sha256'],
                       'sourceSha256': fixture['source']['sha256'], 'variants': variants,
                       'developmentCases': case_stream(fixture['variants'][0]['reports'][0])})
    return result


def check_files(bindings):
    for fixture in bindings:
        name = fixture['id']
        paths = [(f'reconstructions/{name}.py', fixture['candidateSha256']),
                 (f'fixtures/{name}.c', fixture['sourceSha256'])]
        for variant in fixture['variants']:
            paths.extend([(variant['artifact'], variant['sha256']),
                          ('fixtures/harness.c', variant['harnessSha256'])])
        for path, expected in paths:
            if digest((ROOT / path).read_bytes()) != expected:
                raise ValueError(f'Frozen input changed: {path}')


def generator_hash():
    return digest((ROOT / 'lab/pipeline.py').read_bytes() +
                  (ROOT / 'lab/holdout.py').read_bytes())


def freeze(report_path=REPORT, freeze_path=FREEZE):
    record = json.loads(Path(report_path).read_text())
    bindings = identity(record)
    check_files(bindings)
    receipt = {'schemaVersion': 1, 'frozenAt': timestamp(), 'sourceKnown': True,
               'limitation': LIMITATION, 'generatorSha256': generator_hash(),
               'fixtures': bindings,
               'candidateTexts': {f['id']: (ROOT / f"reconstructions/{f['id']}.py").read_text()
                                  for f in bindings}}
    # No evaluation seed is selected or corpus generated by this command.
    write_json(freeze_path, receipt)
    record.pop('evaluation', None)
    for fixture in record['fixtures']:
        for variant in fixture['variants']:
            variant.pop('evaluationReports', None)
    write_json(report_path, record)
    return receipt


def check_freeze(record, receipt):
    if receipt['schemaVersion'] != 1 or receipt['sourceKnown'] is not True:
        raise ValueError('Unsupported freeze receipt')
    if identity(record) != receipt['fixtures']:
        raise ValueError('Recording identity differs from freeze')
    if generator_hash() != receipt['generatorSha256']:
        raise ValueError('Evaluation generator changed after freeze')
    for fixture in receipt['fixtures']:
        if digest(receipt['candidateTexts'][fixture['id']].encode()) != fixture['candidateSha256']:
            raise ValueError('Frozen candidate text changed')
    check_files(receipt['fixtures'])


def fresh_cases(name, seed, count, development):
    if not 1 <= count <= 10000:
        raise ValueError('Evaluation count must be 1..10000 per fixture')
    seen = {case['hex'] for case in development}
    result = []
    skipped = 0
    for case in cases_for(name, seed, count * 4):
        if case['group'] != 'seeded':
            continue
        if case['hex'] in seen:
            skipped += 1
            continue
        seen.add(case['hex'])
        result.append({'id': f'heldout-{len(result):04d}',
                       'label': f'Unseen input {len(result) + 1}',
                       'hex': case['hex'], 'group': 'held-out'})
        if len(result) == count:
            return result, skipped
    raise ValueError('Could not generate enough disjoint unique inputs')


def functions_for(receipt, name):
    namespace = {'__name__': f'frozen_{name}'}
    # Only the owned, allowlisted candidate text with a checked file hash is run.
    exec(compile(receipt['candidateTexts'][name], f'<frozen {name}>', 'exec'), namespace)
    return {candidate: namespace[candidate] for candidate in FIXTURES[name]['candidates']}


def evaluate(report_path=REPORT, freeze_path=FREEZE, count=1000, seed=None):
    record = json.loads(Path(report_path).read_text())
    receipt = json.loads(Path(freeze_path).read_text())
    check_freeze(record, receipt)
    if 'evaluation' in record:
        raise ValueError('Already evaluated; replay existing results or make a new freeze')
    selected_at = timestamp()
    seed_selection = 'system randomness after freeze' if seed is None else 'operator-specified after freeze'
    seed = secrets.randbits(32) if seed is None else seed
    if not isinstance(seed, int) or not 0 <= seed < 2**32:
        raise ValueError('Seed must be an unsigned 32-bit integer')
    if seed == record['seed']:
        raise ValueError('Evaluation seed must differ from development seed')
    skipped = {}
    for fixture, binding in zip(record['fixtures'], receipt['fixtures']):
        name = fixture['id']
        cases, skipped[name] = fresh_cases(name, seed, count, binding['developmentCases'])
        functions = functions_for(receipt, name)
        for variant in fixture['variants']:
            expected = oracle(ROOT / variant['artifact'], cases)
            reports = []
            for baseline in variant['reports']:
                candidate = baseline['id']
                rows = []
                for case, reference in zip(cases, expected):
                    actual = functions[candidate](bytes.fromhex(case['hex']))
                    rows.append({**case, 'expected': reference, 'actual': actual,
                                 'passed': reference == actual})
                failed = sum(not c['passed'] for c in rows)
                reports.append({'id': candidate, 'title': baseline['title'],
                                'intentionalFault': baseline['intentionalFault'],
                                'passed': len(rows)-failed, 'failed': failed, 'total': len(rows),
                                'cases': rows, 'seed': seed, 'caseDigest': stream_digest(cases),
                                'rerun': f'python3 -m lab.holdout replay --fixture {name} --variant {variant["id"]} --candidate {candidate}'})
            variant['evaluationReports'] = reports
    check_freeze(record, receipt)  # Detect modifications during native execution.
    record['evaluation'] = {'frozenAt': receipt['frozenAt'], 'seedSelectedAt': selected_at,
                            'evaluatedAt': timestamp(), 'sourceKnown': True,
                            'seed': seed, 'seedSelection': seed_selection, 'countPerFixture': count,
                            'generatorSha256': receipt['generatorSha256'],
                            'freezePath': 'data/evaluation-freeze.json',
                            'freezeSha256': digest(Path(freeze_path).read_bytes()),
                            'excludedDuplicates': skipped, 'limitation': LIMITATION}
    validate_evaluation(record, receipt)
    write_json(report_path, record)
    return record


def validate_evaluation(record, receipt=None):
    """Validate shipped results without needing native binaries or a compiler."""
    info = record.get('evaluation')
    if not info:
        if any(v.get('evaluationReports') for f in record['fixtures'] for v in f['variants']):
            raise ValueError('Evaluation reports have no freeze metadata')
        return
    if info['sourceKnown'] is not True or info['seed'] == record['seed']:
        raise ValueError('Invalid evaluation disclosure/seed')
    if not info['frozenAt'] <= info['seedSelectedAt'] <= info['evaluatedAt']:
        raise ValueError('Evaluation preceded candidate freeze')
    if receipt is not None:
        if identity(record) != receipt['fixtures'] or info['frozenAt'] != receipt['frozenAt']:
            raise ValueError('Evaluation differs from frozen identity')
        if info['generatorSha256'] != receipt['generatorSha256']:
            raise ValueError('Evaluation generator identity differs from freeze')
        for fixture in receipt['fixtures']:
            if digest(receipt['candidateTexts'][fixture['id']].encode()) != fixture['candidateSha256']:
                raise ValueError('Frozen candidate text changed')
    for fixture in record['fixtures']:
        development = {c['hex'] for c in fixture['variants'][0]['reports'][0]['cases']}
        common = None
        common_expected = None
        for variant in fixture['variants']:
            reports = variant['evaluationReports']
            if [r['id'] for r in reports] != [r['id'] for r in variant['reports']]:
                raise ValueError('Evaluation candidate list mismatch')
            for report in reports:
                cases = case_stream(report)
                inputs = {c['hex'] for c in cases}
                if len(cases) != info['countPerFixture'] or len(inputs) != len(cases) or inputs & development:
                    raise ValueError('Evaluation inputs overlap or are not unique/count-consistent')
                if (len({c['id'] for c in cases}) != len(cases) or
                        any(c['group'] != 'held-out' or len(bytes.fromhex(c['hex'])) > 64 for c in cases)):
                    raise ValueError('Invalid held-out case domain/identity')
                if common is not None and common != cases:
                    raise ValueError('Evaluation corpora differ across candidates/builds')
                common = cases
                expected = [c['expected'] for c in report['cases']]
                if common_expected is not None and common_expected != expected:
                    raise ValueError('Evaluation reference outputs differ across builds')
                common_expected = expected
                if stream_digest(cases) != report['caseDigest'] or report['seed'] != info['seed']:
                    raise ValueError('Evaluation case digest/seed mismatch')
                failed = sum(c['expected'] != c['actual'] for c in report['cases'])
                if (any(c['passed'] != (c['expected'] == c['actual']) for c in report['cases']) or
                        report['failed'] != failed or report['total'] != len(cases) or
                        report['passed'] != len(cases)-failed):
                    raise ValueError('Evaluation result summary mismatch')


def replay(name, variant_id, candidate, case_id=None, report_path=REPORT, freeze_path=FREEZE):
    record = json.loads(Path(report_path).read_text())
    receipt = json.loads(Path(freeze_path).read_text())
    check_freeze(record, receipt)
    info = record['evaluation']
    if digest(Path(freeze_path).read_bytes()) != info['freezeSha256']:
        raise ValueError('Freeze receipt bytes changed')
    validate_evaluation(record, receipt)
    fixture = next(f for f in record['fixtures'] if f['id'] == name)
    variant = next(v for v in fixture['variants'] if v['id'] == variant_id)
    report = next(r for r in variant['evaluationReports'] if r['id'] == candidate)
    cases, _ = fresh_cases(name, info['seed'], info['countPerFixture'],
                          next(f for f in receipt['fixtures'] if f['id'] == name)['developmentCases'])
    if cases != case_stream(report):
        raise ValueError('Regenerated evaluation corpus differs from recording')
    if case_id:
        cases = [c for c in cases if c['id'] == case_id]
        if not cases:
            raise ValueError('Case ID absent from evaluation')
    expected = oracle(ROOT / variant['artifact'], cases)
    function = functions_for(receipt, name)[candidate]
    failures = []
    for case, value in zip(cases, expected):
        actual = function(bytes.fromhex(case['hex']))
        if value != actual:
            failures.append({**case, 'expected': value, 'actual': actual})
    check_freeze(record, receipt)
    return {'total': len(cases), 'passed': len(cases)-len(failures),
            'failed': len(failures), 'failures': failures}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='command', required=True)
    sub.add_parser('freeze', help='Record candidates and development corpora before selecting a new seed')
    evaluation = sub.add_parser('evaluate', help='Execute disjoint inputs on unchanged frozen candidates')
    evaluation.add_argument('--count', type=int, default=1000)
    evaluation.add_argument('--seed', type=int, help='Explicit reproducible seed; default selected from system randomness')
    replay_parser = sub.add_parser('replay')
    replay_parser.add_argument('--fixture', choices=FIXTURES, required=True)
    replay_parser.add_argument('--variant', choices=['O0', 'O2', 'O2-stripped'], required=True)
    replay_parser.add_argument('--candidate', choices=['reconstruct', 'faulty_endian'], required=True)
    replay_parser.add_argument('--case')
    args = parser.parse_args()
    try:
        if args.command == 'freeze':
            result = freeze()
            print(f"Frozen {len(result['fixtures'])} source-known candidates at {result['frozenAt']}; no evaluation seed selected.")
        elif args.command == 'evaluate':
            result = evaluate(count=args.count, seed=args.seed)
            print(json.dumps(result['evaluation'], indent=2))
            for fixture in result['fixtures']:
                for variant in fixture['variants']:
                    print(f"{fixture['id']} / {variant['id']}: " + ', '.join(
                        f"{r['id']} {r['passed']} passed / {r['failed']} failed" for r in variant['evaluationReports']))
        else:
            result = replay(args.fixture, args.variant, args.candidate, args.case)
            print(json.dumps(result, indent=2))
            raise SystemExit(1 if result['failed'] else 0)
    except (ValueError, KeyError, StopIteration, OSError, RuntimeError) as error:
        parser.exit(2, f'Evaluation rejected: {error}\n')


if __name__ == '__main__':
    main()
